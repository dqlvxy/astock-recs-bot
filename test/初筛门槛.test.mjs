/* 初筛门槛 · 确定性单测（2026-11-06）
   运行：node test/初筛门槛.test.mjs
   验证：① 当日涨跌不再是初筛门槛（绿盘 -3% 与高位 9.2% 都照常进入候选）
        ② 仍保留「封死涨停不可买」约束，且 2026-11-09 起按板块取线：
           主板剔除 ≥9.5%（涨停线 9.8 − 0.3）、创业板剔除 ≥19.5%（涨停线 19.8 − 0.3）
        ③ 2026-11-09：量比、换手、连板、流通市值四道关卡已删除，
           极低量比 / 极高换手 / 10 亿小市值 都必须照常入池
        ④ 参数文件中不再存在 追高上限 / 量比上限 / 换手上限 / 连板阈值 键 */
import { scan } from "../engine.js";
import { readFileSync } from "node:fs";

let 通过 = 0, 失败 = 0;
function 断言(名, 条件, 备注) {
  if (条件) { 通过++; console.log("  ✅", 名, 备注 ? "｜" + 备注 : ""); }
  else { 失败++; console.log("  ❌", 名, 备注 ? "｜" + 备注 : ""); }
}

/* 腾讯行情快照字段：f2 价、f3 涨幅、f8 换手、f9 量比、f21 流通市值（元）、f100 行业 */
function 造票(code, chg, 额外) {
  return Object.assign({
    f12: code, f14: "测试" + code, f2: 10, f3: chg, f8: 5, f9: 2, f21: 100 * 1e8, f100: "制造业",
  }, 额外 || {});
}

console.log("一、当日涨跌不再是初筛门槛");
{
  const 票 = [
    造票("600001", -3.0),  // 绿盘：旧版会被「当日必须红盘」剔除，新版应保留
    造票("600002", -0.5),
    造票("600003", 0),
    造票("600004", 5.0),
    造票("600005", 8.5),   // 旧版会被「追高上限」剔除，新版应保留
    造票("600006", 9.2),
  ];
  const 出 = scan(票, []);
  断言("6 只全部进入候选", 出.length === 6, "实际 " + 出.length);
  断言("绿盘 -3% 保留", 出.some((x) => x.code === "600001"));
  断言("平盘 0% 保留", 出.some((x) => x.code === "600003"));
  断言("9.2% 高位保留", 出.some((x) => x.code === "600006"));
  const 绿 = 出.find((x) => x.code === "600001");
  断言("绿盘票的涨幅原值透传", 绿 && 绿.chg === -3.0, 绿 ? "chg=" + 绿.chg : "未入池");
}

console.log("二、封死涨停仍不可买（按板块取线）");
{
  const 出 = scan([造票("600001", 9.6), 造票("600002", 9.9)], []);
  断言("主板 ≥9.5% 剔除", 出.length === 0, "实际 " + 出.length);
  const 主板边界 = scan([造票("600011", 9.4)], []);
  断言("主板 9.4% 保留（未到涨停线）", 主板边界.length === 1, "实际 " + 主板边界.length);

  const 创业 = scan([造票("300001", 12.0), 造票("300002", 15.0), 造票("300003", 19.4)], []);
  断言("创业板 9.5%~19.5% 未封板票保留（2026-11-09 修复误杀）", 创业.length === 3, "实际 " + 创业.length);
  const 创业封板 = scan([造票("300004", 19.6), 造票("300005", 20.0)], []);
  断言("创业板 ≥19.5% 剔除", 创业封板.length === 0, "实际 " + 创业封板.length);

  const 有涨停池 = scan([造票("600003", 9.0)], ["600003"]);
  断言("涨停池内的票剔除（尾盘买不到）", 有涨停池.length === 0, "实际 " + 有涨停池.length);
}

console.log("三、量比 / 换手 / 连板 / 流通市值 四关已删除（2026-11-09）");
{
  断言("量比 0.3（极低）仍入池", scan([造票("600012", 3, { f9: 0.3 })], []).length === 1);
  断言("换手 90%（极高）仍入池", scan([造票("600013", 3, { f8: 90 })], []).length === 1);
  断言("流通市值 10 亿（原下限 20 亿外）仍入池", scan([造票("600014", 3, { f21: 10 * 1e8 })], []).length === 1);
  断言("流通市值 1200 亿（原上限 800 亿外）仍入池", scan([造票("600015", 3, { f21: 1200 * 1e8 })], []).length === 1);
}

console.log("四、其余初筛边界不变（回归）");
{
  断言("涨幅缺失剔除", scan([造票("600001", null)], []).length === 0);
  断言("科创板剔除", scan([造票("688001", 3)], []).length === 0);
  断言("ST 剔除", scan([造票("600005", 3, { f14: "ST测试" })], []).length === 0);
  断言("股价 61 元剔除（>60 上限仍在）", scan([造票("600006", 3, { f2: 61 })], []).length === 0);
}

console.log("四之二、北交所显式剔除（2026-11-09）");
{
  /* 代码段本就不含北交所，此处验证「即使被喂进来也一定剔除」，
     防止日后扩代码段时把 30% 涨跌幅的北交所票混入主板/创业板口径。 */
  断言("430xxx 剔除", scan([造票("430047", 3)], []).length === 0);
  断言("83xxxx 剔除", scan([造票("830799", 3)], []).length === 0);
  断言("87xxxx 剔除", scan([造票("871981", 3)], []).length === 0);
  断言("920 新段剔除", scan([造票("920002", 3)], []).length === 0);
  断言("bj 前缀剔除", scan([造票("830799", 3, { 全码: "bj830799" })], []).length === 0);
  断言("沪深主板 6/0/3 开头不受影响",
    scan([造票("600016", 3), 造票("000016", 3), 造票("300016", 3)], []).length === 3);
}

console.log("五、参数文件不再带已删门槛");
{
  const 参 = JSON.parse(readFileSync(new URL("../params.json", import.meta.url), "utf-8"));
  const cfg = 参.cfg || 参;
  断言("params.json 无 追高上限 键", !("追高上限" in cfg), Object.keys(cfg).join(","));
  断言("params.json 无 量比上限 / 换手上限", !("量比上限" in cfg) && !("换手上限" in cfg), Object.keys(cfg).join(","));
  断言("params.json 无 连板阈值 键", !("连板阈值" in cfg), Object.keys(cfg).join(","));
  断言("仍在的自适应门槛为 温度下限 / 止损率 / 急涨上限",
    "温度下限" in cfg && "止损率" in cfg && "急涨上限" in cfg, Object.keys(cfg).join(","));
}

console.log("\n结果：" + 通过 + " 通过 / " + 失败 + " 失败");
process.exit(失败 ? 1 : 0);
