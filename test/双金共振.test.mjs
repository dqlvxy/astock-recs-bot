let 通过 = 0, 失败 = 0;
function 断言(名, 条件, 备注) {
  if (条件) { 通过++; console.log("  ✅", 名, 备注 ? "｜" + 备注 : ""); }
  else { 失败++; console.log("  ❌", 名, 备注 ? "｜" + 备注 : ""); }
}

/* 连续交易日（跳过周末），UTC 解析，跨时区稳定 */
function 交易日(n) {
  const out = [];
  let d = new Date(Date.UTC(2024, 0, 1));
  while (out.length < n) {
    const w = d.getUTCDay();
    if (w !== 0 && w !== 6) out.push(d.toISOString().slice(0, 10));
    d = new Date(d.getTime() + 86400000);
  }
  return out;
}

/* 按「段」造日 K：[天数, 日涨跌率, 起始价(仅首段)] */
function 造段(段) {
  const 价 = [];
  let c = 段[0][2];
  for (const [天, 率] of 段) for (let i = 0; i < 天; i++) { c *= 率; 价.push(c); }
  const 日 = 交易日(价.length);
  return 价.map((x, i) => ({
    TRADE_DATE: 日[i],
    OPEN_PRICE: i ? 价[i - 1] : x,
    CLOSE_PRICE: x,
    HIGH_PRICE: x * 1.006,
    LOW_PRICE: x * 0.994,
    VOLUME: 100000,
  }));
}

/* 关掉周线均线与临门分支后的基准形态（上一版 B7 口径，用于验证底层链路仍在） */
const 基准段 = [[160, 0.9975, 30], [8, 0.985, 0], [3, 1.045, 0]];
const 周刚翻红段 = [[160, 0.9975, 30], [8, 0.985, 0], [4, 1.045, 0]];
const 旧口径 = { 周均线发散: 0, 周MACD允许临门: 1 };

console.log("一、周 K 聚合规则");
{
  const rows = 造段(基准段);
  const 周 = 聚合成周K(rows);
  断言("周数约为日数 ÷ 5（171 日 → 34~36 周）", 周.length >= 34 && 周.length <= 36, "实际 " + 周.length + " 周 / " + rows.length + " 日");
  断言("首周开盘 = 首日开盘", Math.abs(周[0].OPEN_PRICE - rows[0].OPEN_PRICE) < 1e-9);
  断言("末周收盘 = 末日收盘", Math.abs(周[周.length - 1].CLOSE_PRICE - rows[rows.length - 1].CLOSE_PRICE) < 1e-9);
  断言("周高低包住周内所有日高低", 周.every((w) => w.HIGH_PRICE >= w.LOW_PRICE && w.HIGH_PRICE > 0));
  断言("周日期严格升序", 周.every((w, i) => i === 0 || w.TRADE_DATE > 周[i - 1].TRADE_DATE));
  const 总日量 = rows.reduce((s, r) => s + r.VOLUME, 0);
  const 总周量 = 周.reduce((s, w) => s + w.VOLUME, 0);
  断言("周成交量求和守恒", Math.abs(总日量 - 总周量) < 1e-6, 总日量 + " vs " + 总周量);
}

console.log("二、KDJ「低位 → 聚合 → 向上发散」判定");
{
  const K = [...Array(11).fill(15), 30];
  const D = [...Array(11).fill(14), 20];
  const 命中 = 判断KDJ低位发散({ kArr: K, dArr: D, jArr: K.map((k, i) => 3 * k - 2 * D[i]) }, 20, 8, 5);
  断言("低位聚合后发散 → 命中", !!命中, JSON.stringify(命中));
  if (命中) {
    断言("低位值 ≤ 20", 命中.低位值 <= 20, "低位值 " + 命中.低位值);
    断言("聚合间距 ≤ 8", 命中.聚合间距 <= 8, "聚合间距 " + 命中.聚合间距);
    断言("极差扩大 ≥ 3", 命中.当前间距 >= 命中.聚合间距 + 3, 命中.聚合间距 + " → " + 命中.当前间距);
  }

  const K2 = [...Array(11).fill(60), 75];
  const D2 = [...Array(11).fill(58), 65];
  断言("K 从未 ≤20（高位启动）→ 不命中",
    判断KDJ低位发散({ kArr: K2, dArr: D2, jArr: K2.map((k, i) => 3 * k - 2 * D2[i]) }, 20, 8, 5) === null);

  const K3 = [5, 10, 18, 26, 34, 42, 50, 58, 66, 74, 82, 90];
  const D3 = [4, 8, 14, 20, 26, 32, 38, 44, 50, 56, 62, 68];
  断言("低位但从头到尾未粘合 → 不命中",
    判断KDJ低位发散({ kArr: K3, dArr: D3, jArr: K3.map((k, i) => 3 * k - 2 * D3[i]) }, 20, 8, 5) === null);

  const K4 = [...Array(11).fill(15), 16];
  const D4 = [...Array(11).fill(15), 15.2];
  断言("粘合后发散不足 3 → 不命中",
    判断KDJ低位发散({ kArr: K4, dArr: D4, jArr: K4.map((k, i) => 3 * k - 2 * D4[i]) }, 20, 8, 5) === null);
}

console.log("三、周线 MACD「多头红柱」（临门为可选项）");
{
  const 造MC = (hist) => ({ histArr: hist, difArr: hist.map((x, i) => x / 2 + i * 0.01), deaArr: hist.map(() => 0) });

  const 刚 = 判断周MACD多头(造MC([-1, -0.8, -0.6, -0.4, -0.2, 0.05, 0.1]), 10, false);
  断言("绿转红 → 多头（刚翻红）", 刚 && 刚.状态 === "刚翻红", 刚 && 刚.状态);

  const 延续 = 判断周MACD多头(造MC([0.2, 0.3, 0.35, 0.4, 0.45, 0.5, 0.55]), 10, false);
  断言("持续红柱 → 多头（红柱延续）", 延续 && 延续.状态 === "红柱延续", 延续 && 延续.状态);

  const 临门默认 = 判断周MACD多头(造MC([-1, -0.8, -0.6, -0.4, -0.2, -0.1, -0.05]), 10, false);
  断言("绿柱收窄贴零轴 · 默认关闭临门 → 不算多头", 临门默认 === null);

  const 临门开 = 判断周MACD多头(造MC([-1, -0.8, -0.6, -0.4, -0.2, -0.1, -0.05]), 10, true);
  断言("绿柱收窄贴零轴 · 开启临门 → 即将翻红", 临门开 && 临门开.状态 === "即将翻红");

  const 扩大 = 判断周MACD多头(造MC([-1, -0.8, -0.6, -0.4, -0.3, -0.05, -0.12]), 10, true);
  断言("绿柱重新放大 → 不命中", 扩大 === null);

  const 远离 = 判断周MACD多头(造MC([-2, -1.8, -1.6, -1.4, -1.2, -1.0, -0.9]), 10, true);
  断言("绿柱收窄但距零轴 9%（>0.5%）→ 不命中", 远离 === null);
}

console.log("四、周线均线「多头 + 上行 + 发散」");
{
  const 造收 = (n, 率, 起 = 10) => { const a = []; let c = 起; for (let i = 0; i < n; i++) { c *= 率; a.push(c); } return a; };

  const 多头 = 判断周均线多头发散(造收(40, 1.01));
  断言("稳步上涨 → 多头排列且间距扩大", !!多头, 多头 ? `MA5 ${多头.MA5} > MA10 ${多头.MA10} > MA30 ${多头.MA30}，距 ${多头.上总距} → ${多头.总距}` : "null");

  const 空头 = 判断周均线多头发散(造收(40, 0.99));
  断言("稳步下跌 → 不命中", 空头 === null);

  const 横盘 = 判断周均线多头发散(造收(40, 1.0));
  断言("完全横盘（三线粘合、间距不扩大）→ 不命中", 横盘 === null);

  const 转空 = 判断周均线多头发散([...造收(34, 1.012), ...造收(8, 0.97, 造收(34, 1.012).slice(-1)[0])]);
  断言("前期上涨后期急跌 → 不命中（快线已下穿）", 转空 === null);

  断言("数据不足 32 根 → 返回 null", 判断周均线多头发散(造收(20, 1.01)) === null);

  const 序 = 均线序列([1, 2, 3, 4, 5], 3);
  断言("均线序列前两位为 null", 序[0] === null && 序[1] === null);
  断言("均线序列末位 = 最近 3 项均值", Math.abs(序[4] - 4) < 1e-9, "实际 " + 序[4]);
}

console.log("五、双周期共振端到端（开关组合）");
{
  const rows = 造段(基准段);
  const 收 = rows.map((r) => r.CLOSE_PRICE);
  const mc = macdSeries(收), kdj = kdjSeries(rows), 周 = 周线指标(rows);

  const 旧 = detect双金共振(mc, kdj, 周, 旧口径);
  断言("旧口径（关周线均线、开临门）→ 命中", !!旧,
    旧 ? `日线 ${旧.翻红序} 日前翻红、低位 ${旧.低位值}｜周线 ${旧.周状态}、周低位 ${旧.周低位值}` : "未命中");
  if (旧) {
    断言("日线低位 ≤ 20", 旧.低位值 <= 20, "低位值 " + 旧.低位值);
    断言("周线低位 ≤ 20", 旧.周低位值 <= 20, "周低位值 " + 旧.周低位值);
    断言("周线状态为即将翻红（临门分支）", 旧.周状态 === "即将翻红", 旧.周状态);
    断言("关掉周线均线时 周均线 为 null", 旧.周均线 === null);
  }

  const 严格 = detect双金共振(mc, kdj, 周, { 周均线发散: 1, 周MACD允许临门: 0 });
  断言("严格口径（要周线多头 + 均线发散）→ 该形态不命中（底部反转与趋势多头互斥）", 严格 === null,
    严格 ? "意外命中" : "返回 null");

  /* 核心回归：周线数据不足时，日线再漂亮也不命中 */
  const 短 = 造段([[40, 0.99, 20], [6, 0.988, 0], [2, 1.02, 0]]);
  const 短收 = 短.map((r) => r.CLOSE_PRICE);
  断言("周 K 不足 35 根 → 周线指标 null，且不命中",
    周线指标(短) === null && detect双金共振(macdSeries(短收), kdjSeries(短), 周线指标(短), 旧口径) === null);

  const 跌 = 造段([[180, 0.992, 30]]);
  断言("长期单边下跌 → 不命中",
    detect双金共振(macdSeries(跌.map((r) => r.CLOSE_PRICE)), kdjSeries(跌), 周线指标(跌), 旧口径) === null);

  const 涨 = 造段([[180, 1.004, 10]]);
  断言("长期单边上涨（日线 KDJ 高位）→ 不命中",
    detect双金共振(macdSeries(涨.map((r) => r.CLOSE_PRICE)), kdjSeries(涨), 周线指标(涨), 旧口径) === null);

  /* 周线走「刚翻红」分支：严格的临门关闭，但红柱仍在 → 旧口径下仍命中 */
  const rows2 = 造段(周刚翻红段);
  const r2 = detect双金共振(macdSeries(rows2.map((r) => r.CLOSE_PRICE)), kdjSeries(rows2), 周线指标(rows2), 旧口径);
  断言("末段多涨一日 → 周线红柱（刚翻红）仍命中", !!r2 && r2.周状态 === "刚翻红", r2 ? r2.周状态 : "未命中");
}

console.log("六、前置绿柱门槛（2026-11-10 老板要求 ≥10 根）");
{
  /* 同一形态下只改「前绿最少」，验证门槛真的在拦：
     跌 7 天造出前绿 9 根，旧门槛 3 放行、新门槛 10 拦下。 */
  const rows9 = 造段([[168, 0.9975, 30], [7, 0.985, 0], [3, 1.045, 0]]);
  const 周9 = 周线指标(rows9);
  const mc9 = macdSeries(rows9.map((r) => r.CLOSE_PRICE)), kdj9 = kdjSeries(rows9);
  const 松 = detect双金共振(mc9, kdj9, 周9, { ...旧口径, 前绿最少: 3 });
  const 严 = detect双金共振(mc9, kdj9, 周9, { ...旧口径, 前绿最少: 10 });
  断言("前绿 9 根：旧门槛 3 → 命中", !!松 && 松.前绿 === 9, 松 ? "前绿 " + 松.前绿 : "未命中");
  断言("前绿 9 根：新门槛 10 → 拦下", 严 === null);

  /* 基准段前绿恰好 10 根，新门槛应放行 */
  const rows10 = 造段(基准段);
  const 恰 = detect双金共振(
    macdSeries(rows10.map((r) => r.CLOSE_PRICE)), kdjSeries(rows10), 周线指标(rows10),
    { ...旧口径, 前绿最少: 10 });
  断言("前绿 10 根：新门槛 10 → 命中（边界放行）", !!恰 && 恰.前绿 >= 10, 恰 ? "前绿 " + 恰.前绿 : "未命中");

  /* 默认 CFG 已内置 10，线上不传 opt 也生效 */
  const 默认 = detect双金共振(mc9, kdj9, 周9, { 周均线发散: 0, 周MACD允许临门: 1 });
  断言("不传 opt 时默认门槛 10 生效（前绿 9 被拦）", 默认 === null);
}

