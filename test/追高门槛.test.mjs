/* 追高上限删除 · 确定性单测（2026-11-06）
   运行：node test/追高门槛.test.mjs
   验证：① 当日涨幅不再是初筛门槛（8.5% 的票照常进入候选）
        ② 仍保留「封死涨停不可买」约束（≥9.5% 主板 / ≥9.8% 剔除）
        ③ 参数文件中不再存在 追高上限 键，review 不会把它写回 */
import { scan } from "../engine.js";
import { readFileSync } from "node:fs";

let 通过 = 0, 失败 = 0;
function 断言(名, 条件, 备注) {
  if (条件) { 通过++; console.log("  ✅", 名, 备注 ? "｜" + 备注 : ""); }
  else { 失败++; console.log("  ❌", 名, 备注 ? "｜" + 备注 : ""); }
}

/* 腾讯行情快照字段：f2 价、f3 涨幅、f8 换手、f9 量比、f21 流通市值（元）、f100 行业 */
function 造票(code, chg, 额外) {
  return Object.assign({
    f12: code, f14: "测试" + code, f2: 10, f3: chg, f8: 5, f9: 2, f21: 100 * 1e8, f100: "制造业",
  }, 额外 || {});
}

console.log("一、涨幅不再是初筛门槛");
{
  const 票 = [
    造票("600001", 1.5),
    造票("600002", 5.0),
    造票("600003", 8.5),   // 旧版会被「追高上限 4%」剔除，新版应保留
    造票("600004", 9.2),
  ];
  const 出 = scan(票, []);
  断言("4 只全部进入候选", 出.length === 4, "实际 " + 出.length);
  断言("8.5% 涨幅票保留", 出.some((x) => x.code === "600003"));
  断言("9.2% 涨幅票保留", 出.some((x) => x.code === "600004"));
}

console.log("二、封死涨停仍不可买");
{
  const 出 = scan([造票("600001", 9.6), 造票("600002", 9.9)], []);
  断言("≥9.5% 主板按涨停线剔除", 出.length === 0, "实际 " + 出.length);
  const 有涨停池 = scan([造票("600003", 9.0)], ["600003"]);
  断言("涨停池内的票剔除（尾盘买不到）", 有涨停池.length === 0, "实际 " + 有涨停池.length);
}

console.log("三、其余初筛边界不变（回归）");
{
  断言("绿盘剔除", scan([造票("600001", -1)], []).length === 0);
  断言("量比过低剔除", scan([造票("600002", 3, { f9: 0.3 })], []).length === 0);
  断言("换手过高剔除", scan([造票("600003", 3, { f8: 90 })], []).length === 0);
  断言("市值过小剔除", scan([造票("600004", 3, { f21: 10 * 1e8 })], []).length === 0);
  断言("科创板剔除", scan([造票("688001", 3)], []).length === 0);
  断言("ST 剔除", scan([造票("600005", 3, { f14: "ST测试" })], []).length === 0);
}

console.log("四、参数文件不再带 追高上限");
{
  const 参 = JSON.parse(readFileSync(new URL("../params.json", import.meta.url), "utf-8"));
  const cfg = 参.cfg || 参;
  断言("params.json 无 追高上限 键", !("追高上限" in cfg), Object.keys(cfg).join(","));
  断言("其余硬门槛仍在", "量比上限" in cfg && "换手上限" in cfg && "急涨上限" in cfg);
}

console.log("\n结果：" + 通过 + " 通过 / " + 失败 + " 失败");
process.exit(失败 ? 1 : 0);
